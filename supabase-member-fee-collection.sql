CREATE OR REPLACE FUNCTION public.mark_fee_summary_collected(
  p_summary_id bigint,
  p_allocations jsonb,
  p_paid_date date,
  p_payment_method text,
  p_recorded_by integer DEFAULT NULL,
  p_note text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  summary_row member_fee_summaries%ROWTYPE;
  charge_row charges%ROWTYPE;
  allocation_row member_fee_summary_allocations%ROWTYPE;
  item record;
  paid_for_charge integer;
  new_payment_id integer;
  allocation_total integer;
  linked_paid integer;
  next_status text;
BEGIN
  IF p_paid_date IS NULL THEN
    RAISE EXCEPTION 'Ngày thu không được để trống';
  END IF;

  IF p_payment_method IS NULL
     OR p_payment_method NOT IN ('cash', 'bank_transfer', 'e_wallet', 'other') THEN
    RAISE EXCEPTION 'Phương thức thanh toán không hợp lệ';
  END IF;

  IF p_allocations IS NULL OR jsonb_typeof(p_allocations) <> 'array'
     OR jsonb_array_length(p_allocations) = 0 THEN
    RAISE EXCEPTION 'Chưa có phân bổ khoản thu hợp lệ';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_allocations)
      AS duplicate_item(charge_id integer, component text, amount integer)
    GROUP BY duplicate_item.charge_id, duplicate_item.component
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Phân bổ khoản thu bị trùng';
  END IF;

  SELECT * INTO summary_row
  FROM member_fee_summaries
  WHERE id = p_summary_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy kế hoạch thu';
  END IF;

  IF summary_row.status = 'collected' THEN
    RETURN jsonb_build_object('status', 'already_collected', 'summary_id', p_summary_id);
  END IF;

  IF summary_row.total_due <= 0 THEN
    RAISE EXCEPTION 'Kế hoạch thu không có số tiền hợp lệ';
  END IF;

  FOR item IN
    SELECT *
    FROM jsonb_to_recordset(p_allocations)
      AS allocation_item(charge_id integer, component text, amount integer)
  LOOP
    IF item.charge_id IS NULL OR item.component IS NULL OR btrim(item.component) = ''
       OR item.amount IS NULL OR item.amount <= 0 THEN
      RAISE EXCEPTION 'Phân bổ khoản thu không hợp lệ';
    END IF;

    SELECT * INTO charge_row
    FROM charges
    WHERE charge_id = item.charge_id
      AND member_id = summary_row.member_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Khoản thu không thuộc thành viên của kế hoạch';
    END IF;

    SELECT * INTO allocation_row
    FROM member_fee_summary_allocations
    WHERE summary_id = p_summary_id
      AND charge_id = item.charge_id
      AND component = btrim(item.component)
    FOR UPDATE;

    IF FOUND THEN
      IF allocation_row.allocated_amount <> item.amount THEN
        RAISE EXCEPTION 'Phân bổ retry không khớp với lần trước';
      END IF;
      IF allocation_row.payment_id IS NOT NULL THEN
        CONTINUE;
      END IF;
    ELSE
      INSERT INTO member_fee_summary_allocations (
        summary_id, charge_id, component, allocated_amount
      )
      VALUES (
        p_summary_id, item.charge_id, btrim(item.component), item.amount
      )
      RETURNING * INTO allocation_row;
    END IF;

    SELECT COALESCE(SUM(amount_paid), 0)::integer INTO paid_for_charge
    FROM payments
    WHERE charge_id = charge_row.charge_id;

    IF item.amount > GREATEST(charge_row.amount - paid_for_charge, 0) THEN
      RAISE EXCEPTION 'Số tiền phân bổ vượt công nợ còn lại của khoản thu';
    END IF;

    INSERT INTO payments (
      charge_id,
      amount_paid,
      paid_date,
      payment_method,
      recorded_by,
      note,
      member_fee_summary_id
    )
    VALUES (
      charge_row.charge_id,
      item.amount,
      p_paid_date,
      p_payment_method,
      p_recorded_by,
      p_note,
      p_summary_id
    )
    RETURNING payment_id INTO new_payment_id;

    UPDATE member_fee_summary_allocations
    SET payment_id = new_payment_id
    WHERE id = allocation_row.id;
  END LOOP;

  SELECT COALESCE(SUM(allocated_amount), 0)::integer INTO allocation_total
  FROM member_fee_summary_allocations
  WHERE summary_id = p_summary_id;

  IF allocation_total > summary_row.total_due THEN
    RAISE EXCEPTION 'Tổng phân bổ vượt số tiền kế hoạch';
  END IF;

  SELECT COALESCE(SUM(p.amount_paid), 0)::integer INTO linked_paid
  FROM payments p
  JOIN member_fee_summary_allocations a ON a.payment_id = p.payment_id
  WHERE a.summary_id = p_summary_id;

  IF linked_paid >= summary_row.total_due THEN
    next_status := 'collected';
  ELSIF linked_paid > 0 THEN
    next_status := 'partially_collected';
  ELSE
    next_status := 'planned';
  END IF;

  UPDATE member_fee_summaries
  SET status = next_status,
      collected_at = CASE WHEN next_status = 'collected' THEN COALESCE(collected_at, now()) ELSE NULL END,
      total_paid = LEAST(linked_paid, total_due),
      outstanding = GREATEST(total_due - linked_paid, 0),
      updated_at = now()
  WHERE id = p_summary_id;

  RETURN jsonb_build_object(
    'status', next_status,
    'summary_id', p_summary_id,
    'total_paid', linked_paid,
    'outstanding', GREATEST(summary_row.total_due - linked_paid, 0)
  );
END;
$$;

