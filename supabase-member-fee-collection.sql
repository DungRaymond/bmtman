CREATE TABLE IF NOT EXISTS member_fee_summary_allocations (
  id bigint generated by default as identity primary key,
  summary_id bigint NOT NULL REFERENCES member_fee_summaries(id) ON DELETE RESTRICT,
  charge_id integer NOT NULL REFERENCES charges(charge_id) ON DELETE RESTRICT,
  component text NOT NULL,
  allocated_amount integer NOT NULL CHECK (allocated_amount > 0),
  payment_id integer REFERENCES payments(payment_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (summary_id, charge_id, component)
);

