CREATE TABLE IF NOT EXISTS daily_scorecard_settlement_runs (
  run_id bigint generated by default as identity primary key,
  score_date date not null references daily_scorecards(score_date) on delete restrict,
  status text not null default 'active'
    check (status in ('active', 'settled', 'open_correction', 'aborted')),
  created_at timestamptz not null default now(),
  closed_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS daily_scorecard_settlement_runs_active_idx
  ON daily_scorecard_settlement_runs (score_date)
  WHERE status = 'active';

CREATE INDEX IF NOT EXISTS daily_scorecard_settlement_runs_date_idx
  ON daily_scorecard_settlement_runs (score_date, created_at desc);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'session_stake_points_settlement_run_id_fkey'
      AND conrelid = 'public.session_stake_points'::regclass
  ) THEN
    ALTER TABLE session_stake_points
      ADD CONSTRAINT session_stake_points_settlement_run_id_fkey
      FOREIGN KEY (settlement_run_id)
      REFERENCES daily_scorecard_settlement_runs(run_id)
      ON DELETE SET NULL;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'session_walkins_settlement_run_id_fkey'
      AND conrelid = 'public.session_walkins'::regclass
  ) THEN
    ALTER TABLE session_walkins
      ADD CONSTRAINT session_walkins_settlement_run_id_fkey
      FOREIGN KEY (settlement_run_id)
      REFERENCES daily_scorecard_settlement_runs(run_id)
      ON DELETE SET NULL;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'charges_settlement_run_id_fkey'
      AND conrelid = 'public.charges'::regclass
  ) THEN
    ALTER TABLE charges
      ADD CONSTRAINT charges_settlement_run_id_fkey
      FOREIGN KEY (settlement_run_id)
      REFERENCES daily_scorecard_settlement_runs(run_id)
      ON DELETE SET NULL;
  END IF;
END $$;

