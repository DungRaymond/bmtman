CREATE TABLE IF NOT EXISTS daily_scorecard_reopen_log (
  id bigint generated by default as identity primary key,
  score_date date not null references daily_scorecards(score_date) on delete restrict,
  reopened_at timestamptz not null default now(),
  reason text not null check (char_length(btrim(reason)) > 0),
  previous_settled_at timestamptz not null,
  previous_run_id bigint references daily_scorecard_settlement_runs(run_id) on delete set null
);

CREATE INDEX IF NOT EXISTS daily_scorecard_reopen_log_date_idx
  ON daily_scorecard_reopen_log (score_date, reopened_at desc);

CREATE OR REPLACE FUNCTION public.create_daily_scorecard_settlement_run(p_score_date date)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_settled_at timestamptz;
  v_existing_run bigint;
  v_run_id bigint;
BEGIN
  SELECT settled_at INTO v_settled_at
  FROM daily_scorecards
  WHERE score_date = p_score_date
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy bảng ghi độ của ngày';
  END IF;
  IF v_settled_at IS NOT NULL THEN
    RAISE EXCEPTION 'Ngày này đã chốt sổ độ';
  END IF;

  SELECT run_id INTO v_existing_run
  FROM daily_scorecard_settlement_runs
  WHERE score_date = p_score_date AND status = 'active'
  FOR UPDATE;
  IF v_existing_run IS NOT NULL THEN
    RETURN v_existing_run;
  END IF;

  INSERT INTO daily_scorecard_settlement_runs (score_date, status)
  VALUES (p_score_date, 'active')
  RETURNING run_id INTO v_run_id;
  RETURN v_run_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.finalize_daily_scorecard_settlement(
  p_run_id bigint,
  p_score_date date
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_run daily_scorecard_settlement_runs%ROWTYPE;
  v_settled_at timestamptz;
BEGIN
  SELECT * INTO v_run
  FROM daily_scorecard_settlement_runs
  WHERE run_id = p_run_id AND score_date = p_score_date
  FOR UPDATE;
  IF NOT FOUND OR v_run.status <> 'active' THEN
    RAISE EXCEPTION 'Settlement batch không còn hoạt động';
  END IF;

  SELECT settled_at INTO v_settled_at
  FROM daily_scorecards
  WHERE score_date = p_score_date
  FOR UPDATE;
  IF NOT FOUND OR v_settled_at IS NOT NULL THEN
    RAISE EXCEPTION 'Ngày này đã được chốt hoặc không tồn tại';
  END IF;

  UPDATE daily_scorecards
  SET settled_at = now(), updated_at = now()
  WHERE score_date = p_score_date AND settled_at IS NULL;

  UPDATE daily_scorecard_settlement_runs
  SET status = 'settled', closed_at = now()
  WHERE run_id = p_run_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.abort_daily_scorecard_settlement(p_run_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_run daily_scorecard_settlement_runs%ROWTYPE;
BEGIN
  SELECT * INTO v_run
  FROM daily_scorecard_settlement_runs
  WHERE run_id = p_run_id
  FOR UPDATE;
  IF NOT FOUND OR v_run.status <> 'active' THEN
    RETURN;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM payments p
    JOIN charges c ON c.charge_id = p.charge_id
    WHERE c.settlement_run_id = p_run_id
  ) OR EXISTS (
    SELECT 1
    FROM session_walkins
    WHERE settlement_run_id = p_run_id
      AND fee_type = 'session_fee'
      AND COALESCE(amount_collected, 0) > 0
  ) THEN
    RAISE EXCEPTION 'Settlement batch đã có khoản thu, không thể tự động hủy';
  END IF;

  DELETE FROM session_stake_points WHERE settlement_run_id = p_run_id;
  DELETE FROM charges WHERE settlement_run_id = p_run_id;
  DELETE FROM session_walkins WHERE settlement_run_id = p_run_id;

  UPDATE daily_scorecard_settlement_runs
  SET status = 'aborted', closed_at = now()
  WHERE run_id = p_run_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.reopen_daily_scorecard(
  p_score_date date,
  p_reason text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_settled_at timestamptz;
  v_run daily_scorecard_settlement_runs%ROWTYPE;
  v_log_id bigint;
BEGIN
  IF p_reason IS NULL OR char_length(btrim(p_reason)) = 0 THEN
    RAISE EXCEPTION 'Lý do mở lại không được để trống';
  END IF;

  SELECT settled_at INTO v_settled_at
  FROM daily_scorecards
  WHERE score_date = p_score_date
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy bảng ghi độ của ngày';
  END IF;
  IF v_settled_at IS NULL THEN
    RAISE EXCEPTION 'Ngày này chưa chốt hoặc đã được mở lại';
  END IF;

  PERFORM 1
  FROM monthly_fund_snapshot
  WHERE period_month = to_char(p_score_date, 'YYYY-MM')
    AND closing_balance IS NOT NULL
  FOR UPDATE;
  IF FOUND THEN
    RAISE EXCEPTION 'Tháng này đã chốt số dư, không thể mở lại ngày';
  END IF;

  SELECT * INTO v_run
  FROM daily_scorecard_settlement_runs
  WHERE score_date = p_score_date AND status = 'settled'
  ORDER BY created_at DESC
  LIMIT 1
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Ngày này chưa có settlement batch an toàn để reconcile';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM payments p
    JOIN charges c ON c.charge_id = p.charge_id
    WHERE c.settlement_run_id = v_run.run_id
  ) OR EXISTS (
    SELECT 1
    FROM session_walkins
    WHERE settlement_run_id = v_run.run_id
      AND fee_type = 'session_fee'
      AND COALESCE(amount_collected, 0) > 0
  ) THEN
    RAISE EXCEPTION 'Ngày đã có khoản settlement được thu, cần tạo điều chỉnh trước khi mở lại';
  END IF;

  INSERT INTO daily_scorecard_reopen_log (
    score_date, reason, previous_settled_at, previous_run_id
  )
  VALUES (
    p_score_date, btrim(p_reason), v_settled_at, v_run.run_id
  )
  RETURNING id INTO v_log_id;

  DELETE FROM session_stake_points WHERE settlement_run_id = v_run.run_id;
  DELETE FROM charges WHERE settlement_run_id = v_run.run_id;
  DELETE FROM session_walkins WHERE settlement_run_id = v_run.run_id;

  UPDATE daily_scorecard_settlement_runs
  SET status = 'open_correction', closed_at = now()
  WHERE run_id = v_run.run_id;

  UPDATE daily_scorecards
  SET settled_at = NULL, updated_at = now()
  WHERE score_date = p_score_date AND settled_at IS NOT NULL;

  RETURN jsonb_build_object('log_id', v_log_id, 'score_date', p_score_date);
END;
$$;

CREATE OR REPLACE FUNCTION public.create_walkin_receivables(
  p_session_id integer,
  p_walkin_count integer,
  p_walkin_name text,
  p_amount integer,
  p_settlement_run_id bigint
)
RETURNS SETOF session_walkins
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
  WITH created AS (
    SELECT id
    FROM public.create_walkin_receivables(
      p_session_id, p_walkin_count, p_walkin_name, p_amount
    )
  ), updated AS (
    UPDATE session_walkins sw
    SET settlement_run_id = p_settlement_run_id
    FROM created
    WHERE sw.id = created.id
    RETURNING sw.*
  )
  SELECT * FROM updated;
END;
$$;

