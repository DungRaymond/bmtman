create table if not exists public.daily_member_losses (
  loss_date date not null,
  member_id bigint not null references public.members(member_id) on delete cascade,
  loss_count integer not null default 0 check (loss_count >= 0),
  locked_count integer not null default 0 check (locked_count >= 0),
  paid_count integer not null default 0 check (paid_count >= 0),
  primary key (loss_date, member_id),
  check (paid_count <= locked_count and locked_count <= loss_count)
);

create table if not exists public.pig_ledger (
  id bigint generated by default as identity primary key,
  paid_date date not null,
  member_id bigint not null references public.members(member_id),
  loss_count integer not null check (loss_count > 0),
  amount integer not null check (amount = loss_count * 10000),
  created_at timestamptz not null default now()
);

create table if not exists public.dashboard_expenses (
  id bigint generated by default as identity primary key,
  expense_date date not null,
  amount integer not null check (amount > 0),
  description text not null check (length(trim(description)) between 1 and 160),
  created_at timestamptz not null default now()
);

create table if not exists public.fund_contributions (
  id bigint generated by default as identity primary key,
  paid_date date not null,
  amount integer not null check (amount > 0),
  description text not null check (length(trim(description)) between 1 and 160),
  member_id bigint references public.members(member_id) on delete set null,
  period_month text check (period_month is null or period_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  created_at timestamptz not null default now()
);

