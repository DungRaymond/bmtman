create or replace function public.dashboard_change_loss(p_date date, p_member_id bigint, p_delta integer)
returns integer language plpgsql security definer set search_path = public as $$
declare current_row public.daily_member_losses%rowtype;
begin
  if p_date is null or p_member_id is null or p_delta is null or p_delta not in (-1, 1) then
    raise exception 'invalid loss change';
  end if;
  insert into daily_member_losses(loss_date, member_id) values (p_date, p_member_id)
  on conflict do nothing;
  select * into current_row from daily_member_losses
    where loss_date = p_date and member_id = p_member_id for update;
  if p_delta < 0 and current_row.loss_count <= current_row.locked_count then
    raise exception 'locked loss count';
  end if;
  update daily_member_losses set loss_count = loss_count + p_delta
    where loss_date = p_date and member_id = p_member_id
    returning loss_count into current_row.loss_count;
  return current_row.loss_count;
end;
$$;

create or replace function public.dashboard_lock_losses(p_date date)
returns void language plpgsql security definer set search_path = public as $$
begin
  if p_date is null then raise exception 'invalid date'; end if;
  update daily_member_losses set locked_count = loss_count where loss_date = p_date;
end;
$$;

create or replace function public.dashboard_delete_locked_loss(p_date date, p_member_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare current_row public.daily_member_losses%rowtype;
begin
  select * into current_row from daily_member_losses
    where loss_date = p_date and member_id = p_member_id for update;
  if not found or current_row.locked_count = 0 then raise exception 'no locked count'; end if;
  if current_row.paid_count > 0 then raise exception 'already paid'; end if;
  update daily_member_losses
    set loss_count = loss_count - locked_count, locked_count = 0
    where loss_date = p_date and member_id = p_member_id;
  delete from daily_member_losses
    where loss_date = p_date and member_id = p_member_id and loss_count = 0;
end;
$$;

create or replace function public.dashboard_record_pig_payment(p_date date, p_member_id bigint)
returns integer language plpgsql security definer set search_path = public as $$
declare current_row public.daily_member_losses%rowtype;
        new_count integer;
begin
  select * into current_row from daily_member_losses
    where loss_date = p_date and member_id = p_member_id for update;
  if not found or current_row.locked_count <= current_row.paid_count then
    raise exception 'no unpaid locked losses';
  end if;
  new_count := current_row.locked_count - current_row.paid_count;
  insert into pig_ledger(paid_date, member_id, loss_count, amount)
    values (p_date, p_member_id, new_count, new_count * 10000);
  update daily_member_losses set paid_count = locked_count
    where loss_date = p_date and member_id = p_member_id;
  return new_count * 10000;
end;
$$;

create or replace function public.dashboard_close_pig(p_date date, p_member_id bigint)
returns integer language plpgsql security definer set search_path = public as $$
declare current_row public.daily_member_losses%rowtype;
        new_amount integer;
begin
  if p_date is null or p_member_id is null then raise exception 'invalid pig close'; end if;
  select * into current_row from daily_member_losses
    where loss_date = p_date and member_id = p_member_id for update;
  if not found or current_row.loss_count = 0 then raise exception 'no losses to close'; end if;
  if current_row.paid_count > 0 then raise exception 'losses already partially paid'; end if;
  new_amount := current_row.loss_count * 10000;
  insert into pig_ledger(paid_date, member_id, loss_count, amount)
    values (p_date, p_member_id, current_row.loss_count, new_amount);
  delete from daily_member_losses where loss_date = p_date and member_id = p_member_id;
  return new_amount;
end;
$$;

create or replace function public.dashboard_close_pig_all(p_member_id bigint, p_date date)
returns integer language plpgsql security definer set search_path = public as $$
declare total_amount integer;
begin
  if p_member_id is null or p_date is null then raise exception 'invalid pig close'; end if;
  with closed as (
    delete from daily_member_losses
    where member_id = p_member_id
      and loss_date <= p_date
      and loss_count > paid_count
    returning loss_date, loss_count - paid_count as unpaid_count
  ), paid as (
    insert into pig_ledger(paid_date, member_id, loss_count, amount)
    select loss_date, p_member_id, unpaid_count, unpaid_count * 10000
    from closed
    returning amount
  )
  select coalesce(sum(amount), 0)::integer into total_amount from paid;
  if total_amount = 0 then raise exception 'no losses to close'; end if;
  return total_amount;
end;
$$;

