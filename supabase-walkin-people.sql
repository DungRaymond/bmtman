begin;

create table if not exists walkin_people (
  person_id bigint generated by default as identity primary key,
  display_name text not null,
  normalized_name text not null unique,
  visit_count integer not null default 1 check (visit_count >= 1),
  first_visit_date date not null,
  last_visit_date date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (char_length(display_name) between 1 and 80)
);

alter table session_walkins
  add column if not exists walkin_person_id bigint
  references walkin_people(person_id) on delete set null;

create index if not exists session_walkins_walkin_person_id_idx
  on session_walkins (walkin_person_id);

-- Gom dữ liệu vãng lai có tên đã tồn tại, mỗi buổi chỉ tính một lượt đến.
insert into walkin_people (
  display_name,
  normalized_name,
  visit_count,
  first_visit_date,
  last_visit_date
)
select
  min(btrim(sw.walkin_name)) as display_name,
  lower(regexp_replace(btrim(sw.walkin_name), '\s+', ' ', 'g')) as normalized_name,
  count(distinct sw.session_id)::integer as visit_count,
  min(s.session_date) as first_visit_date,
  max(s.session_date) as last_visit_date
from session_walkins sw
join sessions s on s.session_id = sw.session_id
where nullif(btrim(sw.walkin_name), '') is not null
group by lower(regexp_replace(btrim(sw.walkin_name), '\s+', ' ', 'g'))
on conflict (normalized_name) do update set
  display_name = excluded.display_name,
  visit_count = excluded.visit_count,
  first_visit_date = excluded.first_visit_date,
  last_visit_date = excluded.last_visit_date,
  updated_at = now();

update session_walkins sw
set walkin_person_id = wp.person_id
from walkin_people wp
where nullif(btrim(sw.walkin_name), '') is not null
  and wp.normalized_name = lower(regexp_replace(btrim(sw.walkin_name), '\s+', ' ', 'g'));

create or replace function create_walkin_receivables(
  p_session_id integer,
  p_walkin_count integer,
  p_walkin_name text,
  p_amount integer
)
returns setof session_walkins
language plpgsql
security definer
set search_path = public
as $$
declare
  v_visit_date date;
  v_display_name text;
  v_normalized_name text;
  v_person_id bigint;
  v_first_number integer;
begin
  if p_walkin_count < 1 or p_walkin_count > 30 then
    raise exception 'Số người vãng lai phải từ 1 đến 30';
  end if;
  if p_amount < 5000 or mod(p_amount, 5000) <> 0 then
    raise exception 'Mức thu phải là bội số của 5.000đ';
  end if;

  -- Khóa buổi để hai thao tác đồng thời không nhận cùng walkin_number.
  select session_date
  into v_visit_date
  from sessions
  where session_id = p_session_id
  for update;

  if v_visit_date is null then
    raise exception 'Không tìm thấy buổi chơi';
  end if;

  v_display_name := nullif(regexp_replace(btrim(p_walkin_name), '\s+', ' ', 'g'), '');
  if v_display_name is not null then
    if p_walkin_count <> 1 then
      raise exception 'Chỉ có thể đặt tên khi tạo một người vãng lai';
    end if;
    if char_length(v_display_name) > 80 then
      raise exception 'Tên vãng lai không được quá 80 ký tự';
    end if;

    v_normalized_name := lower(v_display_name);
    select person_id into v_person_id
    from walkin_people
    where normalized_name = v_normalized_name
    for update;

    if v_person_id is null then
      insert into walkin_people (
        display_name,
        normalized_name,
        visit_count,
        first_visit_date,
        last_visit_date
      ) values (
        v_display_name,
        v_normalized_name,
        1,
        v_visit_date,
        v_visit_date
      ) returning person_id into v_person_id;
    else
      if not exists (
        select 1 from session_walkins
        where session_id = p_session_id
          and walkin_person_id = v_person_id
      ) then
        update walkin_people
        set display_name = v_display_name,
            visit_count = visit_count + 1,
            last_visit_date = greatest(last_visit_date, v_visit_date),
            first_visit_date = least(first_visit_date, v_visit_date),
            updated_at = now()
        where person_id = v_person_id;
      end if;
    end if;
  end if;

  select coalesce(max(walkin_number), 0) + 1
  into v_first_number
  from session_walkins
  where session_id = p_session_id;

  return query
  insert into session_walkins (
    session_id,
    walkin_number,
    walkin_name,
    walkin_person_id,
    fee_type,
    amount_expected,
    is_paid,
    amount_collected
  )
  select
    p_session_id,
    v_first_number + n - 1,
    v_display_name,
    v_person_id,
    'session_fee',
    p_amount,
    0,
    null
  from generate_series(1, p_walkin_count) as n
  returning session_walkins.*;
end;
$$;

revoke all on function create_walkin_receivables(integer, integer, text, integer)
  from public, anon, authenticated;
grant execute on function create_walkin_receivables(integer, integer, text, integer)
  to service_role;

commit;
