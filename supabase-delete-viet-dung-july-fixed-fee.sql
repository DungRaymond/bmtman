BEGIN;

-- Huỷ khoản quỹ cố định tháng 07/2026 của Việt Dũng và giao dịch thu sai ngày 01/07/2026.
-- Chạy trong một transaction của Supabase SQL Editor.
-- An toàn và minh bạch:
--   * Chỉ nhắm đúng charge của Việt Dũng, kỳ 2026-07, tạo ngày 2026-07-01.
--   * Lưu bản sao charge/payment vào audit trước khi xoá.
--   * Chặn nếu charge đã được phân bổ vào kế hoạch thu.
--   * Đồng bộ snapshot công nợ; không sửa monthly_fund_snapshot vì hiện không có snapshot liên quan.

CREATE TABLE IF NOT EXISTS charge_deletion_audit (
  audit_id bigint generated by default as identity primary key,
  source_charge_id integer NOT NULL,
  member_id integer NOT NULL,
  member_name text NOT NULL,
  charge_type text NOT NULL,
  amount integer NOT NULL,
  period_month text,
  charge_created_at date,
  payment_total integer NOT NULL DEFAULT 0,
  deletion_reason text NOT NULL,
  deleted_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_charge_id)
);

CREATE TABLE IF NOT EXISTS charge_deletion_payment_audit (
  audit_id bigint generated by default as identity primary key,
  source_payment_id integer NOT NULL,
  source_charge_id integer NOT NULL,
  amount_paid integer NOT NULL,
  paid_date date NOT NULL,
  payment_method text,
  note text,
  deleted_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_payment_id)
);

DO $$
DECLARE
  target_member_id integer;
  target_charge_id integer;
  target_amount integer;
  target_created_at date;
  paid_total integer;
  summary_id bigint;
  summary_status text;
  summary_total_paid integer;
  summary_items jsonb;
  remaining_items jsonb;
  remaining_total integer;
  remaining_paid integer;
  remaining_outstanding integer;
  remaining_status text;
BEGIN
  SELECT member_id
  INTO target_member_id
  FROM members
  WHERE btrim(name) = 'Việt Dũng'
  LIMIT 1;

  IF target_member_id IS NULL THEN
    RAISE EXCEPTION 'Không tìm thấy thành viên Việt Dũng.';
  END IF;

  SELECT c.charge_id, c.amount, c.created_at
  INTO target_charge_id, target_amount, target_created_at
  FROM charges c
  WHERE c.member_id = target_member_id
    AND c.charge_type = 'monthly_fixed_fee'
    AND c.period_month = '2026-07'
    AND c.created_at = '2026-07-01'
  ORDER BY c.charge_id
  LIMIT 1;

  IF target_charge_id IS NULL THEN
    RAISE NOTICE 'Khoản quỹ cố định Việt Dũng ngày 01/07/2026 đã được xử lý hoặc không tồn tại.';
    RETURN;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM member_fee_summary_allocations a
    WHERE a.charge_id = target_charge_id
  ) THEN
    RAISE EXCEPTION
      'DỪNG: charge_id % đã được phân bổ vào kế hoạch thu; hãy gỡ phân bổ trước khi huỷ.',
      target_charge_id;
  END IF;

  SELECT COALESCE(SUM(p.amount_paid), 0)::integer
  INTO paid_total
  FROM payments p
  WHERE p.charge_id = target_charge_id;

  SELECT s.id, s.status, COALESCE(s.total_paid, 0), s.items
  INTO summary_id, summary_status, summary_total_paid, summary_items
  FROM member_fee_summaries s
  WHERE s.member_id = target_member_id
    AND s.period_month = '2026-07'
  FOR UPDATE;

  IF summary_id IS NOT NULL AND summary_total_paid < paid_total THEN
    RAISE EXCEPTION
      'DỪNG: snapshot công nợ ghi nhận ít tiền đã thu (%) hơn payment thực tế (%); cần đối soát thủ công.',
      summary_total_paid, paid_total;
  END IF;

  IF summary_id IS NOT NULL THEN
    SELECT COALESCE(jsonb_agg(item), '[]'::jsonb)
    INTO remaining_items
    FROM jsonb_array_elements(COALESCE(summary_items, '[]'::jsonb)) AS item
    WHERE COALESCE(item->>'component', '') <> 'fixed'
      AND NOT (item->>'name' IN ('Tiền quỹ', 'Tiền quỹ cố định'));

    SELECT COALESCE(SUM((item->>'amount')::integer), 0)::integer
    INTO remaining_total
    FROM jsonb_array_elements(remaining_items) AS item
    WHERE (item->>'amount') ~ '^\d+$';

    remaining_paid := GREATEST(summary_total_paid - paid_total, 0);
    remaining_outstanding := GREATEST(remaining_total - remaining_paid, 0);
    remaining_status := CASE
      WHEN remaining_total > 0 AND remaining_paid >= remaining_total THEN 'collected'
      WHEN remaining_paid > 0 THEN 'partially_collected'
      ELSE 'planned'
    END;

    UPDATE member_fee_summaries
    SET items = remaining_items,
        total_due = remaining_total,
        total_paid = remaining_paid,
        outstanding = remaining_outstanding,
        status = remaining_status,
        collected_at = CASE WHEN remaining_status = 'collected' THEN collected_at ELSE NULL END,
        updated_at = now()
    WHERE id = summary_id;
  END IF;

  INSERT INTO charge_deletion_payment_audit (
    source_payment_id,
    source_charge_id,
    amount_paid,
    paid_date,
    payment_method,
    note
  )
  SELECT p.payment_id, p.charge_id, p.amount_paid, p.paid_date, p.payment_method, p.note
  FROM payments p
  WHERE p.charge_id = target_charge_id
  ON CONFLICT (source_payment_id) DO NOTHING;

  INSERT INTO charge_deletion_audit (
    source_charge_id,
    member_id,
    member_name,
    charge_type,
    amount,
    period_month,
    charge_created_at,
    payment_total,
    deletion_reason
  )
  VALUES (
    target_charge_id,
    target_member_id,
    'Việt Dũng',
    'monthly_fixed_fee',
    target_amount,
    '2026-07',
    target_created_at,
    paid_total,
    'Huỷ khoản quỹ cố định tháng 07/2026 và payment tương ứng theo xác nhận giao dịch thu sai.'
  )
  ON CONFLICT (source_charge_id) DO NOTHING;

  DELETE FROM payments
  WHERE charge_id = target_charge_id;

  DELETE FROM charges
  WHERE charge_id = target_charge_id;

  RAISE NOTICE
    'Đã huỷ charge_id % của Việt Dũng, payment tổng % VND; audit đã lưu, tồn quỹ động đã giảm tương ứng.',
    target_charge_id, paid_total;
END $$;
COMMIT;
