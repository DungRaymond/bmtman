-- Kế hoạch thu vãng lai ở màn hình Tổng hợp và quy tắc quỹ của Chủ tịch.
-- Chạy một lần trong Supabase SQL Editor trước khi deploy code tương ứng.

-- Một số môi trường cũ chưa chạy migration walkin-people; tạo phần phụ thuộc
-- tối thiểu ngay tại đây để migration có thể chạy độc lập và lặp lại an toàn.
CREATE TABLE IF NOT EXISTS public.walkin_people (
  person_id bigint generated by default as identity PRIMARY KEY,
  display_name text NOT NULL,
  normalized_name text NOT NULL UNIQUE,
  visit_count integer NOT NULL DEFAULT 1 CHECK (visit_count >= 1),
  first_visit_date date NOT NULL,
  last_visit_date date NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (char_length(display_name) BETWEEN 1 AND 80)
);

ALTER TABLE public.session_walkins
  ADD COLUMN IF NOT EXISTS walkin_person_id bigint;

CREATE INDEX IF NOT EXISTS session_walkins_walkin_person_id_idx
  ON public.session_walkins (walkin_person_id);

ALTER TABLE public.members
  ADD COLUMN IF NOT EXISTS exclude_fixed_fee_from_fund boolean NOT NULL DEFAULT false;

-- Việt Dũng vẫn có charge/payment tiền quỹ để đối soát như các thành viên khác,
-- nhưng khoản monthly_fixed_fee của anh không được tính vào số dư quỹ.
UPDATE public.members
SET exclude_fixed_fee_from_fund = true
WHERE member_id = 3
  AND lower(btrim(name)) = lower('Việt Dũng');

CREATE TABLE IF NOT EXISTS public.walkin_fee_summaries (
  id bigint generated by default as identity PRIMARY KEY,
  period_month text NOT NULL CHECK (period_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  group_key text NOT NULL,
  walkin_person_id integer REFERENCES public.walkin_people(person_id) ON DELETE SET NULL,
  display_name text NOT NULL,
  total_due integer NOT NULL DEFAULT 0 CHECK (total_due >= 0),
  total_paid integer NOT NULL DEFAULT 0 CHECK (total_paid >= 0),
  outstanding integer NOT NULL DEFAULT 0 CHECK (outstanding >= 0),
  status text NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'collected')),
  collected_at timestamptz,
  paid_date date,
  payment_method text CHECK (payment_method IN ('cash', 'bank_transfer', 'e_wallet', 'other')),
  payment_note text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (total_paid <= total_due),
  CHECK (outstanding = total_due - total_paid)
);

-- Một nhóm chỉ có một kế hoạch đang mở trong một tháng; kế hoạch đã thu được
-- giữ lại để đối soát, và có thể tạo kế hoạch mới nếu còn khoản vãng lai khác.
CREATE UNIQUE INDEX IF NOT EXISTS walkin_fee_summaries_open_plan_key
  ON public.walkin_fee_summaries (period_month, group_key)
  WHERE status = 'planned';

CREATE INDEX IF NOT EXISTS walkin_fee_summaries_period_month_idx
  ON public.walkin_fee_summaries (period_month, status);

CREATE TABLE IF NOT EXISTS public.walkin_fee_summary_items (
  id bigint generated by default as identity PRIMARY KEY,
  summary_id bigint NOT NULL REFERENCES public.walkin_fee_summaries(id) ON DELETE CASCADE,
  session_walkin_id integer NOT NULL REFERENCES public.session_walkins(id) ON DELETE RESTRICT,
  allocated_amount integer NOT NULL CHECK (allocated_amount > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (summary_id, session_walkin_id)
);

CREATE INDEX IF NOT EXISTS walkin_fee_summary_items_walkin_idx
  ON public.walkin_fee_summary_items (session_walkin_id);

CREATE INDEX IF NOT EXISTS walkin_fee_summary_items_summary_idx
  ON public.walkin_fee_summary_items (summary_id);

CREATE OR REPLACE FUNCTION public.prevent_planned_walkin_collection_mutation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF current_setting('app.allow_walkin_plan_collection', true) = 'true' THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM walkin_fee_summary_items item
    JOIN walkin_fee_summaries summary ON summary.id = item.summary_id
    WHERE item.session_walkin_id = OLD.id
      AND summary.status = 'planned'
  ) THEN
    RAISE EXCEPTION 'Khoản vãng lai đã nằm trong kế hoạch thu, hãy sửa kế hoạch tại Tổng hợp';
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS prevent_planned_walkin_collection_mutation ON public.session_walkins;
CREATE TRIGGER prevent_planned_walkin_collection_mutation
  BEFORE UPDATE OR DELETE ON public.session_walkins
  FOR EACH ROW
  EXECUTE FUNCTION public.prevent_planned_walkin_collection_mutation();

CREATE OR REPLACE FUNCTION public.save_walkin_fee_summary_plan(
  p_period_month text,
  p_group_key text,
  p_walkin_person_id integer,
  p_display_name text,
  p_allocations jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  summary_row walkin_fee_summaries%ROWTYPE;
  walkin_row session_walkins%ROWTYPE;
  allocation_item record;
  summary_id bigint;
  conflicting_summary_id bigint;
  allocated_total integer := 0;
  normalized_row_group_key text;
  current_outstanding integer;
BEGIN
  IF p_period_month !~ '^[0-9]{4}-(0[1-9]|1[0-2])$' THEN
    RAISE EXCEPTION 'Tháng áp dụng không hợp lệ';
  END IF;

  IF btrim(COALESCE(p_group_key, '')) = '' OR btrim(COALESCE(p_display_name, '')) = '' THEN
    RAISE EXCEPTION 'Nhóm vãng lai không hợp lệ';
  END IF;

  IF p_allocations IS NULL OR jsonb_typeof(p_allocations) <> 'array' THEN
    RAISE EXCEPTION 'Kế hoạch vãng lai không hợp lệ';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_to_recordset(p_allocations)
      AS duplicate_item(walkin_id integer, amount integer)
    GROUP BY duplicate_item.walkin_id
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Kế hoạch vãng lai có khoản bị lặp';
  END IF;

  SELECT * INTO summary_row
  FROM walkin_fee_summaries
  WHERE period_month = p_period_month
    AND group_key = p_group_key
    AND status = 'planned'
  FOR UPDATE;

  IF jsonb_array_length(p_allocations) = 0 THEN
    IF summary_row.id IS NOT NULL THEN
      DELETE FROM walkin_fee_summaries WHERE id = summary_row.id;
    END IF;
    RETURN NULL;
  END IF;

  IF summary_row.id IS NOT NULL THEN
    summary_id := summary_row.id;
    DELETE FROM walkin_fee_summary_items WHERE summary_id = summary_id;
    UPDATE walkin_fee_summaries
    SET walkin_person_id = p_walkin_person_id,
        display_name = btrim(p_display_name),
        total_due = 0,
        total_paid = 0,
        outstanding = 0,
        paid_date = NULL,
        payment_method = NULL,
        payment_note = NULL,
        collected_at = NULL,
        updated_at = now()
    WHERE id = summary_id;
  ELSE
    INSERT INTO walkin_fee_summaries (
      period_month,
      group_key,
      walkin_person_id,
      display_name,
      total_due,
      total_paid,
      outstanding,
      status
    )
    VALUES (
      p_period_month,
      p_group_key,
      p_walkin_person_id,
      btrim(p_display_name),
      0,
      0,
      0,
      'planned'
    )
    RETURNING id INTO summary_id;
  END IF;

  FOR allocation_item IN
    SELECT *
    FROM jsonb_to_recordset(p_allocations)
      AS item(walkin_id integer, amount integer)
  LOOP
    IF allocation_item.walkin_id IS NULL
       OR allocation_item.amount IS NULL
       OR allocation_item.amount <= 0 THEN
      RAISE EXCEPTION 'Khoản vãng lai được chọn không hợp lệ';
    END IF;

    SELECT * INTO walkin_row
    FROM session_walkins
    WHERE id = allocation_item.walkin_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Không tìm thấy khoản vãng lai';
    END IF;

    normalized_row_group_key := CASE
      WHEN walkin_row.walkin_person_id IS NOT NULL THEN
        'person:' || walkin_row.walkin_person_id::text
      WHEN NULLIF(regexp_replace(btrim(COALESCE(walkin_row.walkin_name, '')), '[[:space:]]+', ' ', 'g'), '') IS NOT NULL THEN
        'name:' || lower(regexp_replace(btrim(walkin_row.walkin_name), '[[:space:]]+', ' ', 'g'))
      ELSE
        'session:' || walkin_row.session_id::text || ':' || walkin_row.walkin_number::text
    END;

    IF normalized_row_group_key <> p_group_key
       OR walkin_row.walkin_person_id IS DISTINCT FROM p_walkin_person_id THEN
      RAISE EXCEPTION 'Khoản vãng lai không thuộc nhóm được chọn';
    END IF;

    current_outstanding := GREATEST(
      walkin_row.amount_expected - COALESCE(walkin_row.amount_collected, 0),
      0
    );
    IF allocation_item.amount > current_outstanding THEN
      RAISE EXCEPTION 'Kế hoạch vượt quá khoản vãng lai còn phải thu';
    END IF;

    SELECT existing_summary.id INTO conflicting_summary_id
    FROM walkin_fee_summary_items existing_item
    JOIN walkin_fee_summaries existing_summary ON existing_summary.id = existing_item.summary_id
    WHERE existing_item.session_walkin_id = walkin_row.id
      AND existing_summary.status = 'planned'
      AND existing_summary.id <> summary_id
    LIMIT 1
    FOR UPDATE OF existing_summary;

    IF conflicting_summary_id IS NOT NULL THEN
      RAISE EXCEPTION 'Khoản vãng lai đã nằm trong một kế hoạch thu khác';
    END IF;

    INSERT INTO walkin_fee_summary_items (summary_id, session_walkin_id, allocated_amount)
    VALUES (summary_id, walkin_row.id, allocation_item.amount);
    allocated_total := allocated_total + allocation_item.amount;
  END LOOP;

  UPDATE walkin_fee_summaries
  SET total_due = allocated_total,
      total_paid = 0,
      outstanding = allocated_total,
      updated_at = now()
  WHERE id = summary_id;

  RETURN summary_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.mark_walkin_fee_summary_collected(
  p_summary_id bigint,
  p_paid_date date,
  p_payment_method text,
  p_note text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  summary_row walkin_fee_summaries%ROWTYPE;
  item_row walkin_fee_summary_items%ROWTYPE;
  walkin_row session_walkins%ROWTYPE;
  current_outstanding integer;
  allocation_total integer;
BEGIN
  IF p_paid_date IS NULL THEN
    RAISE EXCEPTION 'Ngày thu không được để trống';
  END IF;

  IF p_payment_method IS NULL
     OR p_payment_method NOT IN ('cash', 'bank_transfer', 'e_wallet', 'other') THEN
    RAISE EXCEPTION 'Phương thức thanh toán không hợp lệ';
  END IF;

  SELECT * INTO summary_row
  FROM walkin_fee_summaries
  WHERE id = p_summary_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy kế hoạch thu vãng lai';
  END IF;

  IF summary_row.status = 'collected' THEN
    RETURN jsonb_build_object('status', 'already_collected', 'summary_id', p_summary_id);
  END IF;

  IF summary_row.total_due <= 0 THEN
    RAISE EXCEPTION 'Kế hoạch thu vãng lai không có số tiền hợp lệ';
  END IF;

  SELECT COALESCE(SUM(allocated_amount), 0)::integer INTO allocation_total
  FROM walkin_fee_summary_items
  WHERE summary_id = p_summary_id;

  IF allocation_total <> summary_row.total_due THEN
    RAISE EXCEPTION 'Phân bổ kế hoạch vãng lai không khớp tổng tiền';
  END IF;

  PERFORM set_config('app.allow_walkin_plan_collection', 'true', true);

  FOR item_row IN
    SELECT *
    FROM walkin_fee_summary_items
    WHERE summary_id = p_summary_id
    ORDER BY id
  LOOP
    SELECT * INTO walkin_row
    FROM session_walkins
    WHERE id = item_row.session_walkin_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Không tìm thấy khoản vãng lai trong kế hoạch';
    END IF;

    current_outstanding := GREATEST(
      walkin_row.amount_expected - COALESCE(walkin_row.amount_collected, 0),
      0
    );
    IF item_row.allocated_amount > current_outstanding THEN
      RAISE EXCEPTION 'Khoản vãng lai đã thay đổi, hãy kiểm tra lại kế hoạch';
    END IF;

    UPDATE session_walkins
    SET amount_collected = COALESCE(amount_collected, 0) + item_row.allocated_amount,
        is_paid = 1
    WHERE id = walkin_row.id;
  END LOOP;

  UPDATE walkin_fee_summaries
  SET total_paid = total_due,
      outstanding = 0,
      status = 'collected',
      collected_at = now(),
      paid_date = p_paid_date,
      payment_method = p_payment_method,
      payment_note = NULLIF(btrim(p_note), ''),
      updated_at = now()
  WHERE id = p_summary_id;

  RETURN jsonb_build_object(
    'status', 'collected',
    'summary_id', p_summary_id,
    'total_paid', summary_row.total_due,
    'outstanding', 0
  );
END;
$$;

