create table if not exists member_fee_summaries (
  id bigint generated by default as identity primary key,
  member_id integer not null references members(member_id) on delete cascade,
  period_month text not null check (period_month ~ '^\\d{4}-(0[1-9]|1[0-2])$'),
  member_status text not null check (member_status in ('fixed', 'former_fixed')),
  items jsonb not null default '[]'::jsonb,
  total_due integer not null default 0,
  total_paid integer not null default 0,
  outstanding integer not null default 0,
  updated_at timestamptz not null default now(),
  unique (member_id, period_month),
  check (jsonb_typeof(items) = 'array')
);

create index if not exists member_fee_summaries_period_month_idx
  on member_fee_summaries (period_month, member_status);

